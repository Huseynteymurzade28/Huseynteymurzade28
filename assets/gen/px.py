"""Tiny pixel-art toolkit shared by the scene generators: a canvas of hex
colours, sprite blitting from ASCII maps, a 5px pixel font, and an SVG writer
that emits one <path> per colour (plus optional animated overlay layers).

No dependencies.
"""

class Canvas:
    def __init__(s, w, h, bg=None):
        s.w, s.h = w, h
        s.g = [[bg] * w for _ in range(h)]
        s.e = [[False] * w for _ in range(h)]      # emissive: lighting leaves these alone

    def px(s, x, y, c, e=False):
        if 0 <= x < s.w and 0 <= y < s.h and c is not None:
            s.g[y][x] = c
            s.e[y][x] = e

    def get(s, x, y):
        return s.g[y][x] if 0 <= x < s.w and 0 <= y < s.h else None

    def rect(s, x, y, w, h, c, e=False):
        for j in range(y, y + h):
            for i in range(x, x + w):
                s.px(i, j, c, e)

    def box(s, x, y, w, h, fill, line):
        s.rect(x, y, w, h, line)
        s.rect(x + 1, y + 1, w - 2, h - 2, fill)

    def blit(s, x, y, rows, key, emit="", flip=False):
        for j, row in enumerate(rows):
            if flip:
                row = row[::-1]
            for i, ch in enumerate(row):
                if ch not in ". ":
                    s.px(x + i, y + j, key[ch], ch in emit)

    def text(s, x, y, string, c, e=False):
        for ch in string:
            g = FONT.get(ch, FONT["?"])
            for j, row in enumerate(g):
                for i, bit in enumerate(row):
                    if bit == "#":
                        s.px(x + i, y + j, c, e)
            x += len(g[0]) + 1
        return x


def text_width(string):
    return sum(len(FONT.get(ch, FONT["?"])[0]) + 1 for ch in string) - 1


def _paths(cv):
    by = {}
    for j, row in enumerate(cv.g):
        i = 0
        while i < cv.w:
            c = row[i]
            if c is None:
                i += 1
                continue
            k = i
            while k < cv.w and row[k] == c:
                k += 1
            by.setdefault(c, []).append(f"M{i} {j}h{k - i}v1h-{k - i}z")
            i = k
    return "".join(f'<path fill="{c}" d="{"".join(d)}"/>' for c, d in by.items())


def svg(base, overlays=(), scale=4, label="", css="", rx=0):
    """base: Canvas. overlays: [(Canvas with None background, css class)]."""
    W, H = base.w, base.h
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W * scale}" '
           f'height="{H * scale}" shape-rendering="crispEdges" role="img" aria-label="{label}">']
    if css:
        out.append(f"<style>{css}</style>")
    if rx:
        out.append(f'<clipPath id="r"><rect width="{W}" height="{H}" rx="{rx}"/></clipPath><g clip-path="url(#r)">')
    out.append(_paths(base))
    for cv, cls in overlays:
        out.append(f'<g class="{cls}">{_paths(cv)}</g>')
    if rx:
        out.append("</g>")
    out.append("</svg>\n")
    return "\n".join(out)


def hexrgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def rgbhex(c):
    return "#%02x%02x%02x" % tuple(max(0, min(255, round(v))) for v in c)


def mix(a, b, t):
    return tuple(a[i] + (b[i] - a[i]) * t for i in range(3))


